                    <h2 class="titulohistoria">O que é o Câncer?</h2>
                    <p class="textonoticia" style="text-align: justify;">
                        O câncer é um grupo de doenças caracterizadas pelo crescimento descontrolado de células anormais no
                        corpo. Essas células podem se multiplicar de forma desorganizada, invadir tecidos próximos e se
                        espalhar para outras partes do corpo, processo conhecido como metástase. Existem mais de 100 tipos
                        diferentes de câncer, afetando diversos órgãos e sistemas do corpo, como pulmões, mama, intestino,
                        próstata, pele, entre outros.
                        <br><br>
                        Embora as causas exatas do câncer não sejam totalmente compreendidas, ele é amplamente associado a
                        fatores genéticos e ambientais. Isso significa que fatores como genética, estilo de vida e exposições ambientais podem aumentar ou reduzir o risco de desenvolvimento de câncer.
                        <br><br>
                        Fatores de Risco
                        A identificação de fatores de risco é fundamental para a prevenção e o diagnóstico precoce do câncer. Alguns fatores são modificáveis, ou seja, podem ser controlados com mudanças no estilo de vida, enquanto outros são inevitáveis, como a predisposição genética. Os principais fatores de risco incluem:
                        <br><br>
                        1. Tabagismo
                        O uso de tabaco é o maior fator de risco para o câncer de pulmão, mas também está associado a cânceres de boca, garganta, esôfago, pâncreas, bexiga, rim e outros. O fumo passivo (a exposição à fumaça de cigarro) também é prejudicial à saúde e aumenta o risco de câncer em não-fumantes.
                        <br><br>
                        2. Alimentação e Sedentarismo
                        Uma dieta rica em alimentos processados, gorduras saturadas, carne vermelha e pobre em frutas, vegetais e fibras pode aumentar o risco de câncer, especialmente câncer de cólon, mama e fígado. Além disso, a falta de atividade física está relacionada ao aumento do risco de vários tipos de câncer, como mama, cólon e endométrio.
                        <br><br>
                        3. Exposição ao Sol
                        A exposição excessiva ao sol e ao uso inadequado de camas de bronzeamento aumenta o risco de câncer de pele, incluindo o melanoma, que é o tipo mais grave de câncer de pele. A proteção solar e o uso de roupas adequadas são fundamentais para prevenir esses riscos.
                        <br><br>
                        4. Consumo de Álcool
                        O consumo excessivo de álcool está relacionado ao aumento do risco de câncer de fígado, boca, garganta, esôfago e mama, além de câncer de cólon e reto.
                        <br><br>
                        5. Exposição a Produtos Químicos e Radiação
                        A exposição a substâncias tóxicas e carcinogênicas, como radiação ionizante, produtos químicos industriais, pesticidas e outros agentes ambientais, pode aumentar o risco de desenvolvimento de câncer. Trabalhadores de certos setores, como construção, mineração e indústria petroquímica, podem estar mais expostos a esses riscos.
                        <br>
                        6. Histórico Familiar e Genética
                        Alguns tipos de câncer, como mama, cólon e ovário, podem ter um componente genético. Ter um histórico familiar de câncer aumenta as chances de uma pessoa desenvolver a doença, especialmente quando o câncer ocorre em idades mais jovens. A genética também pode influenciar como o corpo reage a fatores ambientais e de estilo de vida.
                        <br><br>
                        Prevenção do Câncer
                        Embora não seja possível eliminar totalmente o risco de câncer, diversas medidas podem ser adotadas para prevenir a doença ou detectá-la precocemente, quando o tratamento tem maior chance de sucesso. As principais formas de prevenção incluem:
                        <br><br>
                        1. Adoção de Hábitos Saudáveis
                        A adoção de um estilo de vida saudável é uma das formas mais eficazes de reduzir o risco de câncer. Isso inclui:
                        <br><br>
                        Alimentação Balanceada: Manter uma dieta rica em frutas, vegetais, grãos integrais e proteínas magras. Limitar o consumo de alimentos processados, carnes vermelhas e gorduras saturadas.
                        Atividade Física Regular: A prática de exercícios físicos regulares (pelo menos 150 minutos de atividade moderada por semana) pode reduzir o risco de vários tipos de câncer, além de ajudar no controle de peso.
                        Evitar o Tabagismo: Parar de fumar é a melhor maneira de reduzir o risco de câncer de pulmão e outros tipos relacionados ao tabaco.
                        Redução do Consumo de Álcool: Limitar o consumo de bebidas alcoólicas pode diminuir o risco de cânceres relacionados ao álcool, como câncer de fígado, boca, garganta e mama.
                        <br><br>
                        2. Proteção Solar
                        Evitar a exposição excessiva ao sol, principalmente nos horários de pico (entre 10h e 16h), e usar protetor solar com fator de proteção adequado (FPS 30 ou superior) é fundamental para prevenir o câncer de pele. Também é importante usar roupas de proteção, chapéus e óculos de sol.
                        <br><br>
                        3. Vacinação
                        Algumas vacinas podem ajudar a prevenir certos tipos de câncer. A vacina contra o HPV (Papilomavírus Humano) pode prevenir o câncer de colo de útero, além de outros tipos relacionados a esse vírus, como câncer de garganta, ânus e pênis. A vacina contra a hepatite B pode prevenir o câncer de fígado.
                        <br><br>
                        4. Exames de Rastreamento
                        O diagnóstico precoce pode salvar vidas. O rastreamento de certos tipos de câncer pode ser feito antes que os sintomas apareçam, aumentando as chances de tratamento bem-sucedido. Os exames de rastreamento recomendados incluem:
                        <br><br>
                        Mamografia para o câncer de mama (geralmente a partir dos 40 anos, conforme orientação médica).
                        Papanicolau (Pap Smear) para detecção precoce do câncer de colo de útero.
                        Exame de Sangue Oculto nas Fezes para o câncer de cólon e reto (geralmente a partir dos 50 anos).
                        Exame de Prostata (PSA) para o câncer de próstata (conforme orientação médica, a partir dos 50 anos ou antes, se houver histórico familiar).
                        5. Consulta Regular ao Médico
                        Consultas periódicas ao médico para avaliar a saúde de forma geral e realizar os exames recomendados são essenciais para identificar fatores de risco e sinais precoces de câncer. Além disso, é importante estar atento a qualquer mudança no corpo, como nódulos, sangramentos inexplicáveis, perda de peso não intencional ou dores persistentes, e procurar um médico imediatamente.
                        <br><br>
                        Conscientização e Educação
                        A conscientização sobre o câncer é um passo crucial na luta contra a doença. Ao informar a população sobre os fatores de risco, a importância da prevenção e os métodos de diagnóstico precoce, podemos reduzir o impacto do câncer na sociedade. A Fundação do Câncer está comprometida com a educação, promovendo campanhas de conscientização sobre os riscos, sintomas e formas de prevenção do câncer.
                        <br><br>
                        Juntos, podemos diminuir a incidência de câncer e salvar vidas. A prevenção começa com a informação!
